const UNKNOWN: readonly string[] = ['##.', '..#', '.#.', '...', '.#.']

export const BRANCH_SPRITE: readonly string[] = ['#...#', '#...#', '#..#.', '#.#..', '##...']

export const GLYPH_WIDTH = 3

export function bitmap(text: string): string[] {
  const rows = ['', '', '', '', '']
  ;[...text.toUpperCase()].forEach((ch, i) => {
    const glyph = GLYPHS[ch] ?? UNKNOWN
    glyph.forEach((line, r) => {
      rows[r] += (i > 0 ? '.' : '') + line
    })
  })
  return rows
}

// Packs pixel rows two at a time into half-block cells: 5 pixel rows -> 3 text rows.
export function pack(pixels: readonly string[]): string[] {
  const out: string[] = []
  for (let r = 0; r < pixels.length; r += 2) {
    const top = pixels[r] ?? ''
    const bottom = pixels[r + 1] ?? ''
    let line = ''
    for (let c = 0; c < top.length; c += 1) {
      const t = top[c] === '#'
      const b = bottom[c] === '#'
      line += t && b ? '█' : t ? '▀' : b ? '▄' : ' '
    }
    out.push(line)
  }
  return out
}

export function pixelText(text: string): string[] {
  return pack(bitmap(text))
}

export function pixelWidth(chars: number): number {
  return chars === 0 ? 0 : chars * (GLYPH_WIDTH + 1) - 1
}
